// 랭킹전 시험: 순위가 높은 친구만 도전할 수 있는지, 도전하면 바로 붙는지, 고르지 않은 학생은 자동으로 붙는지, 보너스가 들어가는지
const { spawn } = require('child_process');
const path = require('path'), os = require('os'), fs = require('fs');
const { io } = require('socket.io-client');
const PORT = 3312, URL = 'http://localhost:' + PORT;
const DATA_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'puyo-r-'));
const srv = spawn('node', [path.join(__dirname, '..', 'server.js')], { env: Object.assign({}, process.env, { PORT, FAST: '1', TEACHER_PASSWORD: 'test', DATA_DIR }), stdio: ['ignore', 'pipe', 'inherit'] });
const wait = ms => new Promise(r => setTimeout(r, ms));
const emit = (s, ev, d) => new Promise(r => s.emit(ev, d || {}, x => r(x || {})));
let fails = 0; const ok = (c, m) => { console.log((c ? '  ✔ ' : '  ✘ ') + m); if (!c) fails++; };

(async () => {
  await new Promise(r => srv.stdout.on('data', d => { if (String(d).includes('사이언스')) r(); }));
  const t = io(URL, { transports: ['websocket'] });
  await emit(t, 't:login', { pw: 'test' });
  const { code } = await emit(t, 't:newClass', { name: '시험 1반' });
  const names = ['일등', '이등', '삼등', '사등', '오등'];
  const st = [];
  for (const n of names) {
    const s = io(URL, { transports: ['websocket'], forceNew: true });
    const o = { s, name: n, events: [] };
    s.on('state', v => { o.view = v; });
    s.on('challenged', d => o.events.push('challenged:' + d.from));
    s.on('feed', f => o.events.push('feed:' + f));
    const r = await emit(s, 'join', { code, name: n }); o.id = r.view.id; o.view = r.view;
    st.push(o); await wait(30);
  }
  console.log('▶ 랭킹전 켜기');
  const set = await emit(t, 't:settings', { code, settings: { challenge: true } });
  ok(set.settings.challenge && set.settings.mode === 2, '랭킹전 켜짐 (1:1)');
  await emit(t, 't:start', { code }); await wait(400);
  const v = st[4].view;
  ok(v.rankMode && v.ladder && v.ladder.length === 5, '학생 화면에 랭킹전 사다리가 와요');
  const pos = Object.fromEntries(v.ladder.map(x => [x.name, x.pos]));
  ok(pos['일등'] === 1 && pos['오등'] === 5, '같은 점수면 먼저 들어온 순서로 줄 세우기');
  const low = await emit(st[2].s, 'challenge', { target: st[3].id });
  ok(low.err, '낮은 순위(4위)는 고를 수 없어요: ' + low.err);
  const self = await emit(st[0].s, 'challenge', { target: st[0].id });
  ok(self.err, '1위는 도전할 상대가 없어요');
  const up = await emit(st[4].s, 'challenge', { target: st[0].id });
  ok(up.ok, '5위가 1위에게 도전');
  await wait(400);
  ok(st[0].events.some(e => e === 'challenged:오등'), '1위에게 도전 알림이 가요');
  const tv = await emit(t, 't:open', { code });
  const rm = tv.view.matches.find(m => m.ranked);
  ok(rm && rm.ranked.cName === '오등' && rm.ranked.dName === '일등', '도전하자마자 랭킹전 대결이 열려요 (5위→1위)');
  ok(tv.view.matches.length === 1, '나머지는 고를 시간을 기다려요');
  await wait(2200);
  const tv2 = await emit(t, 't:open', { code });
  ok(tv2.view.matches.length === 3, `고르지 않은 학생은 자동으로 짝 (경기 ${tv2.view.matches.length}개: 랭킹전 1 + 자동 1 + AI 1)`);
  ok(tv2.view.matches.filter(m => m.ranked).length === 1, '자동 짝은 랭킹전이 아니에요');
  ok(st.some(o => o.events.some(e => e.startsWith('feed:') && e.includes('랭킹전 시작'))), '반 전체에 랭킹전 시작 소식');
  console.log('▶ 경기 끝 → 보너스');
  await emit(t, 't:endMatch', { id: rm.id }); await wait(300);
  const rec = await emit(t, 't:records', { code });
  const rows = rec.results.filter(x => x.ranked);
  const winner = rows.find(x => x.rank === 1);
  ok(rows.length === 2 && winner && winner.bonus === (winner.ranked === '도전' ? 10 : 5), `이긴 쪽 보너스: ${winner && winner.ranked} 성공 +${winner && winner.bonus}`);
  console.log('▶ 랭킹전 끄기');
  await emit(st[3].s, 'challenge', { target: st[1].id });
  await emit(t, 't:settings', { code, settings: { challenge: false } }); await wait(300);
  ok(!st[3].view.rankMode && !st[3].view.myChallenge, '끄면 도전 신청이 모두 지워지고 자동 배정으로 돌아가요');
  await emit(t, 't:settings', { code, settings: { mode: 3 } }); await emit(t, 't:settings', { code, settings: { challenge: true } });
  const s3 = await emit(t, 't:settings', { code, settings: {} });
  ok(s3.settings.mode === 2, '랭킹전은 항상 1:1');
  console.log('▶ 데스매치');
  await emit(t, 't:settings', { code, settings: { challenge: false, mode: 2, matchMin: 0 } });
  await emit(t, 't:stop', { code }); await emit(t, 't:start', { code }); await wait(1500);
  const dv = await emit(t, 't:open', { code });
  const dm = dv.view.matches.find(m => m.state !== 'ended');
  ok(dm && dm.death, '데스매치 경기가 열려요');
  await wait(7000);
  const dv2 = await emit(t, 't:open', { code });
  const dm2 = dv2.view.matches.find(m => m.id === dm.id);
  ok(dm2 && (dm2.state !== 'ended' || dm2.players.some(p => !p.alive)), '시간이 지나도 끝나지 않고, 한 명이 탈락해야 끝나요');
  ok(dm2 && dm2.sprint, '오래 걸리면 공격 2배(막판 스퍼트)로 바뀌어요');
  console.log(fails ? `\n✘ ${fails}개 실패` : '\n✔ 랭킹전 시험 통과');
  st.forEach(o => o.s.close()); t.close(); srv.kill(); process.exit(fails ? 1 : 0);
})().catch(e => { console.error(e); srv.kill(); process.exit(1); });
